#!/usr/bin/env python3
"""Generate ``IconBrowserIcons.lua`` from the client's icon textures.

Every file below ``Interface\\Icons\\`` in the client archives becomes one
entry. An icon found in any archive other than ``patch-I.MPQ`` is tagged
``stock`` (3.3.5a); an icon found only in ``patch-I.MPQ`` is tagged
``reforged``. Names are deduplicated case-insensitively and sorted.

Usage::

    python3 tools/icon-browser/gen_icon_list.py
    python3 tools/icon-browser/gen_icon_list.py --check
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent / "client-patch"))

from mpq import Archive, MpqError, archive_chain  # noqa: E402

ICON_PREFIX = "interface\\icons\\"
ICON_SUFFIXES = (".blp", ".tga")
REFORGED_ARCHIVE = "patch-i.mpq"
REFORGED_MARKER = "#"

HEADER = """\
-- Generated by tools/icon-browser/gen_icon_list.py. Do not edit by hand.
-- Source: every Interface\\Icons\\* .blp or .tga texture in the client archives.
--
-- One entry per line: a quoted icon name.
-- A trailing "#" marks a Reforged icon (patch-I.MPQ only, no stock archive
-- ships it). Every other icon is stock 3.3.5a. Strip the "#" before building
-- the texture path: Interface\\Icons\\<name>.
--
-- Sorted case-insensitively, deduplicated case-insensitively.
-- Regenerate: python3 tools/icon-browser/gen_icon_list.py
"""


class IconListError(RuntimeError):
    """The icon list cannot be built from the given client."""


def icon_name(entry_name: str) -> str | None:
    """Return the icon name for an archive entry, or ``None`` when not an icon.

    ``Interface\\Icons\\<name>.blp`` becomes ``<name>``. Subdirectories below
    ``Icons`` and unknown extensions are not icon textures and are skipped.
    """
    # mpq.list_files() leaves the archive's separator as stored, and some archives use "/".
    entry_name = entry_name.replace("/", "\\")
    lower = entry_name.lower()
    if not lower.startswith(ICON_PREFIX):
        return None
    rest = entry_name[len(ICON_PREFIX) :]
    if "\\" in rest or "/" in rest:
        return None
    for suffix in ICON_SUFFIXES:
        if rest.lower().endswith(suffix):
            name = rest[: -len(suffix)]
            return name or None
    return None


def is_reforged_archive(archive_name: str) -> bool:
    return Path(archive_name).name.lower() == REFORGED_ARCHIVE


def merge_icons(archives) -> dict[str, tuple[str, str]]:
    """Merge ``(archive_name, entry_names)`` pairs into ``{lower: (name, tag)}``.

    An icon present in a stock archive wins over the same icon in
    ``patch-I.MPQ``, regardless of the archive order or name casing.
    """
    chosen: dict[str, tuple[tuple[int, str], str, str]] = {}
    for archive_name, entries in archives:
        reforged = is_reforged_archive(archive_name)
        rank = 1 if reforged else 0
        tag = "reforged" if reforged else "stock"
        for entry in entries:
            name = icon_name(entry)
            if not name:
                continue
            key = name.lower()
            if not reforged and name.endswith(REFORGED_MARKER):
                raise IconListError(f"stock icon name ends with the Reforged marker: {name!r}")
            candidate = ((rank, name), name, tag)
            current = chosen.get(key)
            if current is None or candidate[0] < current[0]:
                chosen[key] = candidate
    return {key: (value[1], value[2]) for key, value in chosen.items()}


def lua_string(name: str) -> str:
    return '"' + name.replace("\\", "\\\\").replace('"', '\\"') + '"'


def render(icons: dict[str, tuple[str, str]]) -> str:
    """Render the Lua data file; deterministic for a given icon set."""
    lines = [HEADER.rstrip("\n"), "IconBrowserIcons = {"]
    for name, tag in sorted(icons.values(), key=lambda item: (item[0].lower(), item[0])):
        key = name + REFORGED_MARKER if tag == "reforged" else name
        lines.append(lua_string(key) + ",")
    lines.append("}")
    return "\n".join(lines) + "\n"


def counts(icons: dict[str, tuple[str, str]]) -> tuple[int, int, int]:
    stock = sum(1 for _, tag in icons.values() if tag == "stock")
    return len(icons), stock, len(icons) - stock


def is_stale(path: Path, text: str) -> bool:
    """True when ``path`` is missing or differs from ``text``."""
    try:
        return path.read_bytes() != text.encode("utf-8")
    except FileNotFoundError:
        return True


def load_client_icons(client_root: str) -> dict[str, tuple[str, str]]:
    """Walk the client archives below ``client_root`` and return merged icons."""
    client = Path(client_root).expanduser()
    data_dir = client if client.name.lower() == "data" else client / "Data"
    if not data_dir.is_dir():
        raise IconListError(f"client Data directory not found: {data_dir}")

    archives = archive_chain(data_dir)
    if not archives:
        raise IconListError(f"no MPQ archives found in: {data_dir}")

    listed = []
    for archive_path in archives:
        try:
            with Archive(archive_path) as archive:
                listed.append((archive_path.name, [entry.name for entry in archive.list_files()]))
        except (MpqError, OSError) as error:
            # A stock archive can own icons alone, or share them with patch-I. Skipping it
            # silently would drop icons from the list or flip them to the wrong source tag,
            # and --check would then report the lossy file as up to date.
            raise IconListError(f"cannot read {archive_path.name}: {error}") from error
    if not listed:
        raise IconListError(f"no readable MPQ archives in: {data_dir}")
    icons = merge_icons(listed)
    if not icons:
        raise IconListError(
            f"no Interface\\Icons entries in {data_dir}; the archives may list no files"
        )
    return icons


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--client",
        default="~/Games/wotlk-clean",
        help="3.3.5a client root (default: ~/Games/wotlk-clean)",
    )
    parser.add_argument(
        "--out",
        default=str(HERE / "IconBrowserIcons.lua"),
        help="Lua data file to write or check",
    )
    parser.add_argument(
        "--check",
        action="store_true",
        help="exit non-zero when the output file is stale",
    )
    args = parser.parse_args(argv)

    try:
        icons = load_client_icons(args.client)
    except (IconListError, OSError) as error:
        print(f"error: {error}", file=sys.stderr)
        return 2

    text = render(icons)
    total, stock, reforged = counts(icons)
    out = Path(args.out).expanduser()

    if args.check:
        if is_stale(out, text):
            print(f"error: {out} is stale; run python3 tools/icon-browser/gen_icon_list.py", file=sys.stderr)
            return 1
        print(f"icons: {total} (stock {stock}, reforged {reforged})")
        print(f"{out}: up to date")
        return 0

    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_bytes(text.encode("utf-8"))
    print(f"icons: {total} (stock {stock}, reforged {reforged})")
    print(f"wrote {out} ({len(text.encode('utf-8')) / 1024:.1f} KiB)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
